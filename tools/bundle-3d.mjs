/*
 * Bundles src/scene3d.src.js (which imports three) into js/scene3d.js.
 *
 * Three.js is a real dependency, chosen deliberately, but only the pieces the
 * constellation actually uses are shipped: esbuild tree-shakes the import list
 * down from the full library. The output is a plain IIFE that sets
 * window.WhichAIScene, so the rest of the site keeps its no-modules,
 * no-bundler shape and js/scene3d.js can be committed and served as-is.
 *
 * Run: node tools/bundle-3d.mjs      (the production build runs it for you)
 */
import { build } from "esbuild";
import { writeFile, readFile } from "node:fs/promises";
import { gzipSync } from "node:zlib";
import path from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const OUT = path.join(ROOT, "js", "scene3d.js");

const res = await build({
  entryPoints: [path.join(ROOT, "src", "scene3d.src.js")],
  bundle: true,
  format: "iife",
  target: ["es2018"],
  charset: "utf8",
  legalComments: "none",
  minify: true,
  write: false,
  logLevel: "silent"
});

const banner = "/* WhichAI model constellation - generated by tools/bundle-3d.mjs from src/scene3d.src.js. Do not edit by hand. Bundles the used parts of three.js (MIT, (c) three.js authors). */\n";
const code = banner + res.outputFiles[0].text;
await writeFile(OUT, code);

const bytes = Buffer.byteLength(code);
const gz = gzipSync(Buffer.from(code)).length;
console.log("js/scene3d.js  " + (bytes / 1024).toFixed(1) + " KB  (" + (gz / 1024).toFixed(1) + " KB gzipped)");
if (!code.includes("WhichAIScene")) { console.error("BUNDLE CHECK FAILED: global not exported"); process.exit(1); }
